export type PixelIconName = keyof typeof ICONS;

export const PIXEL_ICON_SIZE = 12;

export interface PixelRun {
  x: number;
  y: number;
  w: number;
}

const cache = new Map<PixelIconName, PixelRun[]>();

/** The icon's filled pixels as horizontal runs, in a 12×12 grid. */
export function pixelRuns(name: PixelIconName): PixelRun[] {
  const hit = cache.get(name);
  if (hit) return hit;
  const runs: PixelRun[] = [];
  ICONS[name].forEach((row, y) => {
    let x = 0;
    while (x < PIXEL_ICON_SIZE) {
      if (row[x] !== "#") {
        x++;
        continue;
      }
      let w = 0;
      while (x + w < PIXEL_ICON_SIZE && row[x + w] === "#") w++;
      runs.push({ x, y, w });
      x += w;
    }
  });
  cache.set(name, runs);
  return runs;
}

/** The same runs as one SVG path `d` (handy for a single <path> element). */
export function pixelPath(name: PixelIconName): string {
  return pixelRuns(name)
    .map((r) => `M${r.x} ${r.y}h${r.w}v1h-${r.w}z`)
    .join("");
}
